def safe(value):
    """
    Escape text before inserting it into HTML.
    Empty values display as an em dash.
    """
    text = escape(str(value or "").strip())
    return text or "—"


def peso(amount):
    """
    Format a number as Philippine peso.

    Example:
        1500 -> ₱1,500.00
    """
    return f"₱{float(amount or 0):,.2f}"


def limit_text(value):
    """
    None means there is no database limit.
    """
    if value is None:
        return "Unlimited"

    return f"{value:,}"


def full_name(person):
    parts = [
        person.get("first_name"),
        person.get("middle_name"),
        person.get("last_name"),
    ]

    return " ".join(
        part
        for part in parts
        if part
    )


def is_valid_email(email):
    name, _, domain = email.partition("@")

    return (
        bool(name)
        and "." in domain
        and " " not in email
    )


def find_missing(required):
    """
    required looks like:
        {"Field label": value}

    Returns labels for empty values.
    """
    return [
        label
        for label, value in required.items()
        if not value.strip()
    ]


def get_amount(subscription):
    if subscription.get("billing_cycle") == "Yearly":
        return float(
            subscription.get("price_yearly") or 0
        )

    return float(
        subscription.get("price_monthly") or 0
    )


