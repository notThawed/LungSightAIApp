def render_progress():

    current = (
        st.session_state.client_application_step
    )

    total = len(APPLICATION_STEPS)

    percent = round(
        current / total * 100
    )

    if current + 1 < total:
        up_next = (
            f"Next: "
            f"{APPLICATION_STEPS[current + 1][1]}"
        )
    else:
        up_next = "Last step"

    steps_html = ""

    for number, (
        short_name,
        _,
    ) in enumerate(APPLICATION_STEPS):

        if number < current:
            state = "done"
            mark = "✓"

        elif number == current:
            state = "current"
            mark = number + 1

        else:
            state = "todo"
            mark = number + 1

        steps_html += (
            f"<div class='ls-step ls-step-{state}'>"
            f"<span class='ls-dot'>{mark}</span>"
            f"<span class='ls-step-name'>{short_name}</span>"
            "</div>"
        )

    st.markdown(
        "<div class='ls-progress'>"
        "<div class='ls-progress-top'>"
        "<div>"
        f"<p class='ls-progress-title'>"
        f"Step {current + 1} of {total}"
        "</p>"
        f"<p class='ls-progress-meta'>{up_next}</p>"
        "</div>"
        f"<div class='ls-progress-percent'>"
        f"{percent}%"
        "<small>complete</small>"
        "</div>"
        "</div>"
        "<div class='ls-bar'>"
        f"<div class='ls-bar-fill' style='width:{percent}%'>"
        "</div>"
        "</div>"
        f"<div class='ls-steps'>{steps_html}</div>"
        "</div>",
        unsafe_allow_html=True,
    )


