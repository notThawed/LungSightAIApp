def rows_html(rows):
    """
    Create label/value rows for review and payment summaries.
    """

    items = "".join(
        f"<div class='ls-row'>"
        f"<span>{label}</span>"
        f"<b>{safe(value)}</b>"
        f"</div>"
        for label, value in rows
    )

    return (
        f"<div class='ls-rows'>"
        f"{items}"
        f"</div>"
    )


