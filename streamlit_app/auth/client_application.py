def render_subscription_confirmation():

    step_header(
        "Selected subscription",
        "Confirm the plan you chose and how you would like to be billed.",
    )

    subscription = (
        st.session_state
        .client_application["subscription"]
    )

    monthly = float(
        subscription.get(
            "price_monthly"
        ) or 0
    )

    yearly = float(
        subscription.get(
            "price_yearly"
        ) or 0
    )

    with st.container(
        key="plan_summary"
    ):

        st.markdown(
            "<p class='ls-plan-label'>"
            "Your selected plan"
            "</p>"
            f"<p class='ls-plan-name'>"
            f"{safe(subscription.get('plan_name'))}"
            "</p>",
            unsafe_allow_html=True,
        )

        billing_cycle = st.radio(
            "Billing cycle",
            ["Monthly", "Yearly"],
            index=(
                0
                if subscription.get(
                    "billing_cycle"
                ) == "Monthly"
                else 1
            ),
            horizontal=True,
            key="application_billing_cycle",
        )

        subscription[
            "billing_cycle"
        ] = billing_cycle

        if billing_cycle == "Yearly":
            price = yearly
            period = "year"
        else:
            price = monthly
            period = "month"

        st.markdown(
            f"<p class='ls-plan-price'>"
            f"{peso(price)}"
            f"<small> / {period}</small>"
            f"</p>",
            unsafe_allow_html=True,
        )

        savings = (
            monthly * 12
            - yearly
        )

        if (
            billing_cycle == "Yearly"
            and yearly > 0
            and savings > 0
        ):

            st.markdown(
                f"<p class='ls-plan-savings'>"
                f"You save {peso(savings)} "
                "compared with paying monthly."
                f"</p>",
                unsafe_allow_html=True,
            )

        st.markdown(
            limits_html(subscription),
            unsafe_allow_html=True,
        )

    note(
        "Your subscription will be activated once the "
        "LungSight team approves this application."
    )

    if nav_buttons(
        "subscription",
        1,
    ):
        go_to_step(3)


